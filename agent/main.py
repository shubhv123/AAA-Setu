import io
import os
import base64
import logging
from typing import Dict, Any, Optional
import httpx
from agent.gnani_config import (
    get_auth_headers,
    GNANI_STT_REST_URL,
    GNANI_TTS_REST_URL,
    TIMBRE_VOICES,
    DEFAULT_SAMPLE_RATE,
)
from agent.evon_client import EvonClient
from agent.tools import (
    stage_asha_to_anmol_queue,
    commit_anm_vhsnd_record,
)

logger = logging.getLogger("aaa_setu.agent")

class VoiceAgentPipeline:
    def __init__(self):
        self.evon_client = EvonClient()

    async def transcribe_audio(
        self,
        audio_bytes: bytes,
        language_code: str = "hi-IN",
        filename: str = "input.wav"
    ) -> str:
        """
        Transcribes audio using Gnani Prisma v3.0 STT via REST with ITN format='transcribe'.
        Surfaces raw API errors directly if request fails.
        """
        if len(audio_bytes) < 4:
            raise ValueError(f"Audio file is too short ({len(audio_bytes)} bytes)")

        header = audio_bytes[:4]
        logger.info(f"Received audio file for STT ({len(audio_bytes)} bytes). Header magic: {header}")

        # Check if client accidentally sent WebM (EBML: 0x1A 0x45 0xDF 0xA3)
        if header == b"\x1a\x45\xdf\xa3":
            logger.error("Received WebM audio instead of WAV. WebM cannot be parsed by Prisma's WAV demuxer.")
            raise ValueError(
                "Client sent WebM audio instead of PCM WAV. The browser must record using 16kHz PCM WAV with standard RIFF header."
            )

        headers = get_auth_headers()
        # Remove Content-Type so multipart boundary is auto-generated by httpx
        headers.pop("Content-Type", None)

        data = {
            "model": "prisma-v3.0",
            "language_code": language_code,
            "format": "transcribe",  # Inverse Text Normalization for numeric vitals (142/92, 8.4)
            "itn_native_numerals": "false"  # Return Arabic numerals for BP/Hb indicators
        }
        files = {
            "audio_file": (filename, audio_bytes, "audio/wav")
        }

        logger.info(f"Calling Gnani Prisma STT at {GNANI_STT_REST_URL} (language: {language_code})...")
        async with httpx.AsyncClient(timeout=45.0) as client:
            resp = await client.post(GNANI_STT_REST_URL, headers=headers, data=data, files=files)
            if resp.status_code != 200:
                err_text = resp.text
                logger.error(f"Prisma STT error HTTP {resp.status_code}: {err_text}")
                raise RuntimeError(f"Gnani Prisma STT Error [HTTP {resp.status_code}]: {err_text}")

            result = resp.json()
            # Prisma v3.0 typically returns { "transcript": "...", "confidence": ... } or { "text": "..." }
            transcript = result.get("transcript") or result.get("text") or ""
            return transcript.strip()

    async def synthesize_speech(
        self,
        text: str,
        language_code: str = "hi-IN",
        voice: Optional[str] = None
    ) -> bytes:
        """
        Synthesizes spoken audio alert using Gnani Timbre v2.5.
        Surfaces raw API errors directly if request fails.
        """
        headers = get_auth_headers()
        headers["Content-Type"] = "application/json"

        selected_voice = voice or TIMBRE_VOICES.get(language_code, "Nalini")
        payload = {
            "text": text,
            "voice": selected_voice,
            "model": "timbre-v2.5",
            "language": language_code,
            "audio_config": {
                "sample_rate": DEFAULT_SAMPLE_RATE,
                "encoding": "linear_pcm",
                "container": "wav"
            }
        }

        logger.info(f"Calling Gnani Timbre TTS at {GNANI_TTS_REST_URL} (voice: {selected_voice})...")
        async with httpx.AsyncClient(timeout=45.0) as client:
            resp = await client.post(GNANI_TTS_REST_URL, headers=headers, json=payload)
            if resp.status_code != 200:
                err_text = resp.text
                logger.error(f"Timbre TTS error HTTP {resp.status_code}: {err_text}")
                raise RuntimeError(f"Gnani Timbre TTS Error [HTTP {resp.status_code}]: {err_text}")

            return resp.content

    async def process_frontline_relay(
        self,
        audio_bytes: Optional[bytes] = None,
        spoken_text: Optional[str] = None,
        source_role: str = "ASHA_RELAY",
        language_code: str = "hi-IN",
        offline_poshan: bool = False
    ) -> Dict[str, Any]:
        """
        End-to-End Frontline Relay Pipeline:
        1. Transcribe audio using Prisma v3.0 (if audio provided).
        2. Extract clinical indicators using Evon v3.3.
        3. Dispatch to deterministic tools (ANMOL queue, Poshan sync, Paper register).
        4. Synthesize spoken regional alert using Timbre v2.5.
        """
        # Step 1: STT
        if audio_bytes and not spoken_text:
            transcript = await self.transcribe_audio(audio_bytes, language_code=language_code)
        elif spoken_text:
            transcript = spoken_text
        else:
            raise ValueError("Either audio_bytes or spoken_text must be provided.")

        logger.info(f"Transcript received: '{transcript}'")

        # Step 2: Clinical Data Extraction via Evon v3.3
        extracted = await self.evon_client.extract_asha_visit_update(transcript)
        logger.info(f"Extracted indicators: {extracted}")

        # Step 3: Tool Execution based on Role
        if source_role == "ASHA_RELAY":
            # Skill 1: Stage to ANMOL queue (zero write access for ASHA)
            tool_res = await stage_asha_to_anmol_queue(
                asha_worker_name=extracted.get("asha_worker_name") or "Geeta Devi",
                beneficiary_name=extracted.get("beneficiary_name") or "Sunita Devi",
                rch_id=extracted.get("rch_id") or "999000104829",
                gestational_month=extracted.get("gestational_month"),
                mcp_card_last_bp=extracted.get("mcp_card_last_bp"),
                mcp_card_last_hb=float(extracted["mcp_card_last_hb"]) if extracted.get("mcp_card_last_hb") is not None else None,
                home_danger_signs=extracted.get("home_danger_signs") or [],
                ifa_tablets_remaining=extracted.get("ifa_tablets_remaining"),
                joint_visit_number=extracted.get("joint_visit_number"),
                offline_poshan=offline_poshan
            )
        else:
            # Skill 2: Commit ANM VHSND record
            bp_val = extracted.get("mcp_card_last_bp") or "120/80"
            systolic, diastolic = (int(x) for x in bp_val.split("/")[:2]) if "/" in bp_val else (120, 80)
            hb_val = float(extracted.get("mcp_card_last_hb") or 11.0)

            tool_res = await commit_anm_vhsnd_record(
                anm_worker_name="Nurse Kavita",
                rch_id=extracted.get("rch_id") or "999000104830",
                beneficiary_name=extracted.get("beneficiary_name") or "Meena Kumari",
                anc_visit_number=2,
                measured_bp_systolic=systolic,
                measured_bp_diastolic=diastolic,
                measured_hb_g_dl=hb_val,
                weight_kg=54.0,
                urine_albumin="negative",
                ifa_tablets_issued=30,
                tt_booster_given=True
            )

        # Step 4: Spoken Audio Response with Timbre v2.5
        triage_info = tool_res["triage"]
        spoken_action = triage_info["action_hindi"]

        audio_b64 = None
        try:
            tts_audio_bytes = await self.synthesize_speech(
                text=spoken_action,
                language_code=language_code
            )
            audio_b64 = base64.b64encode(tts_audio_bytes).decode("utf-8")
        except Exception as e:
            logger.warning(f"Could not generate TTS audio: {e}")
            # If TTS fails, error is logged and audio_b64 is None, but tool execution is retained

        return {
            "transcript": transcript,
            "extracted": extracted,
            "triage": triage_info,
            "poshan": tool_res.get("poshan"),
            "paper_register": tool_res.get("paper_register"),
            "queue_id": tool_res.get("queue_id"),
            "spoken_audio_b64": audio_b64,
            "status": tool_res.get("status")
        }

